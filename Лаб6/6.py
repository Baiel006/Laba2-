from abc import ABC, abstractmethod

#  Абстрактный класс

class AbstractTask(ABC):
    def __init__(self, x=0):
        """
        Конструктор абстрактного класса.
        Атрибут:
            x (int): введённое число, по умолчанию = 0
        """
        self.x = x

    @abstractmethod
    def run_task(self):
        """
        Абстрактный метод, который должен быть реализован
        в дочерних классах для выполнения конкретных действий.
        """
        pass


#  Класс с описанием всех функций из первого задания

class TaskFunctions:
    def repeat_string(self):
        """
        Задание для чисел 1–3:
        Пользователь вводит строку и количество повторений.
        Программа выводит строку заданное количество раз.
        """
        s = input("Введите строку: ")
        n = int(input("Введите количество повторов: "))
        for i in range(n):
            print(s)

    def power_number(self):
        """
        Задание для чисел 4–6:
        Пользователь вводит степень, программа возводит x в эту степень
        и выводит пример вида "x в степени n = результат".
        """
        m = int(input("Введите степень: "))
        result = self.x ** m
        print(f"{self.x} в степени {m} = {result}")

    def increase_number(self):
        """
        Задание для чисел 7–9:
        Увеличивает значение x на 1 десять раз и выводит результат.
        """
        for i in range(10):
            self.x += 1
            print(self.x)


#  Конечный класс, наследующий оба предыдущих

class FinalTask(AbstractTask, TaskFunctions):
    def __init__(self, x=0):
        """
        Конструктор конечного класса.
        Наследует атрибут x и сразу запускает метод run_task().
        """
        super().__init__(x)
        self.run_task()

    def run_task(self):
        """
        Определяет, какое действие выполнить в зависимости от x:
            1–3 → повтор строки
            4–6 → возведение в степень
            7–9 → увеличение числа
        """
        if 1 <= self.x <= 3:
            self.repeat_string()
        elif 4 <= self.x <= 6:
            self.power_number()
        elif 7 <= self.x <= 9:
            self.increase_number()
        else:
            print("Ошибка ввода")


#  Запуск программы
if __name__ == "__main__":
    while True:
        # Ввод числа пользователем
        x = int(input("\nВведите число от 1 до 9: "))

        # Создание объекта конечного класса и выполнение действия
        FinalTask(x)

        # Спрашиваем, хочет ли пользователь продолжить
        choice = input("\nВведите 1 — продолжить, 0 — завершить: ")

        if choice == "0":
            print("Программа завершена.")
            break